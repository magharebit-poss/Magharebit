['ar', 'fr', 'en'].forEach(lang => {
  const filePath = path.join(MESSAGES_DIR, lang + '.json');
  const messages = JSON.parse(fs.readFileSync(filePath, 'utf8'));
  if (messages.auth) {
    console.log(lang + ': auth namespace already present — skipping');
    return;
  }
  messages.auth = AUTH[lang];
  fs.writeFileSync(filePath, JSON.stringify(messages, null, 2) + '\n');
  console.log(lang + ': added auth namespace (' + Object.keys(AUTH[lang]).length + ' keys)');
});

console.log('Done.');
