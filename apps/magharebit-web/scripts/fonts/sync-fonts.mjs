// Copies the variable fonts we self-host into public/fonts and writes src/app/fonts.css.
//
// Source: the @fontsource-variable packages (SIL Open Font License 1.1), unpacked anywhere, e.g.
//   npm pack @fontsource-variable/cairo@5 @fontsource-variable/noto-naskh-arabic@5 @fontsource-variable/plus-jakarta-sans@5
//   (then extract each .tgz into a folder of the same name)
// Run:  node scripts/fonts/sync-fonts.mjs <folder containing the extracted packages>
//
// Why variable fonts: one file per family and subset covers every weight (the per-weight static
// files cost 3-4x more requests). Family names stay 'Cairo', 'Noto Naskh Arabic' and
// 'Plus Jakarta Sans', so all existing font-family strings keep working.
import { copyFileSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const SRC = process.argv[2]
if (!SRC) { console.error('usage: node scripts/fonts/sync-fonts.mjs <dir>'); process.exit(1) }

const FAMILIES = [
  { pkg: 'cairo', family: 'Cairo', subsets: ['arabic', 'latin-ext', 'latin'] },
  { pkg: 'noto-naskh-arabic', family: 'Noto Naskh Arabic', subsets: ['arabic', 'latin-ext', 'latin'] },
  { pkg: 'plus-jakarta-sans', family: 'Plus Jakarta Sans', subsets: ['latin-ext', 'latin'] },
]
const OUT_FONTS = 'public/fonts'
mkdirSync(OUT_FONTS, { recursive: true })

const dirs = readdirSync(SRC)
let css = '/* Generated by scripts/fonts/sync-fonts.mjs. Do not edit by hand. */\n'
const files = {}
for (const f of FAMILIES) {
  const dir = dirs.find((d) => d.startsWith(`fontsource-variable-${f.pkg}-`) && !d.endsWith('.tgz'))
  if (!dir) throw new Error(`package for ${f.pkg} not found in ${SRC}`)
  const pkgDir = join(SRC, dir, 'package')
  const version = JSON.parse(readFileSync(join(pkgDir, 'package.json'), 'utf8')).version
  const source = readFileSync(join(pkgDir, 'wght.css'), 'utf8')
  for (const subset of f.subsets) {
    const block = source.split('@font-face').find((b) => b.includes(`/files/${f.pkg}-${subset}-wght-normal.woff2`))
    if (!block) throw new Error(`${f.pkg} ${subset} not in wght.css`)
    const weight = block.match(/font-weight:\s*([^;]+);/)[1]
    const range = block.match(/unicode-range:\s*([^;]+);/)[1]
    // Version in the file name: the files are served with an immutable cache header.
    const file = `${f.pkg}-${subset}-wght-v${version}.woff2`
    copyFileSync(join(pkgDir, 'files', `${f.pkg}-${subset}-wght-normal.woff2`), join(OUT_FONTS, file))
    files[`${f.pkg}-${subset}`] = `/fonts/${file}`
    css += `\n@font-face {\n  font-family: '${f.family}';\n  font-style: normal;\n  font-display: swap;\n  font-weight: ${weight};\n  src: url('/fonts/${file}') format('woff2');\n  unicode-range: ${range};\n}\n`
  }
  copyFileSync(join(pkgDir, 'LICENSE'), join(OUT_FONTS, `LICENSE-${f.pkg}.txt`))
  console.log(`${f.family} ${version}: ${f.subsets.join(', ')}`)
}
writeFileSync('src/app/fonts.css', css)
// Font URLs for <link rel="preload">, so a font upgrade cannot leave a stale preload behind.
writeFileSync('src/lib/font-files.ts',
  '// Generated by scripts/fonts/sync-fonts.mjs. Do not edit by hand.\n' +
  `export const FONT_FILES = ${JSON.stringify(files, null, 2).replace(/"([a-z-]+)":/g, "'$1':").replace(/"/g, "'")} as const\n`)
console.log('wrote src/app/fonts.css and src/lib/font-files.ts')
